import { geoGraticule10, geoPath, type GeoSphere } from 'd3-geo';
import { WORLD_LAND } from '../../logic/data/worldLand';
import { createSphereFittedProjection } from './logic/createSphereFittedProjection';

const MAP_WIDTH = 960;
const MAP_HEIGHT = 480;

const SPHERE: GeoSphere = { type: 'Sphere' };
const GRATICULE = geoGraticule10();

const projection = createSphereFittedProjection({ width: MAP_WIDTH, height: MAP_HEIGHT });
const pathGenerator = geoPath(projection);

const spherePath = pathGenerator(SPHERE) ?? '';
const graticulePath = pathGenerator(GRATICULE) ?? '';
const landPath = pathGenerator(WORLD_LAND) ?? '';

export default function SphereAndGraticuleTab() {
  return (
    <div className='flex flex-col gap-4 w-full'>
      <div className='text-sm text-gray-600 dark:text-gray-300 flex flex-col gap-2'>
        <p>Same land, same projection. Two new layers are drawn under it:</p>

        <ol className='list-decimal pl-6 flex flex-col gap-1'>
          <li>
            <strong>The sphere.</strong> <code>{'{ type: "Sphere" }'}</code> isn&apos;t standard GeoJSON. It&apos;s a d3
            extension that means &quot;the entire globe&quot;. Its outline is the edge of the projection, and every
            point on Earth lands inside it.
          </li>
          <li>
            <strong>The graticule.</strong> Lines of longitude and latitude every 10°, generated by{' '}
            <code>geoGraticule10()</code> as a single <code>MultiLineString</code>. Most meridians stop at ±80° to avoid
            clutter near the poles; only the ones every 90° run all the way.
          </li>
        </ol>

        <p>
          All three layers go through <strong>one shared projection</strong>. That&apos;s what keeps them lined up: if
          the land were fitted on its own (as in the previous tab), it would sit about 8px off the grid, because the
          land doesn&apos;t reach the North Pole. The difference is too small to see here, but it would be a visible
          misalignment in other projections.
        </p>

        <p>
          The straight line along the bottom of the previous tab wasn&apos;t a frame. It was Antarctica&apos;s outline
          running along the South Pole, which equirectangular stretches from a single point into a full-width line. Here
          it lines up with the sphere&apos;s bottom edge.
        </p>

        <p>
          On the map, the graticule is a grid of perfect squares: one degree is the same distance everywhere, in both
          directions. On the real Earth it isn&apos;t, which is exactly the distortion this projection hides. Other
          projections bend this grid.
        </p>
      </div>

      <svg
        viewBox={`0 0 ${MAP_WIDTH} ${MAP_HEIGHT}`}
        overflow='visible'
        role='img'
        aria-label='Outline of the world land masses over a 10 degree graticule'
      >
        <path d={spherePath} fill='none' stroke='currentColor' strokeWidth={1.5} />
        <path d={graticulePath} fill='none' stroke='currentColor' strokeWidth={0.5} strokeOpacity={0.25} />
        <path d={landPath} fill='none' stroke='currentColor' strokeWidth={0.75} />
      </svg>
    </div>
  );
}
